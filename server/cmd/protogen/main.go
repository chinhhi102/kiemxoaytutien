// Command protogen sinh bộ mã hoá/giải mã nhị phân cho CẢ HAI phía từ một nguồn schema.
//
//	cd server && go run ./cmd/protogen
//
// NETCODE_SPEC §4.9 bắt buộc có bước này trước khi bật Protocol v2, và lý do rất cụ thể:
// viết `DataView` bằng tay ở hai phía là hai bản dịch của cùng một tài liệu. Chúng lệch nhau
// trong im lặng — không có lỗi nào được ném ra, client chỉ đọc rác.
//
// Sinh ra:
//
//	server/internal/wire/wire_gen.go
//	client/src/net/wire.gen.ts
package main

import (
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"

	"kiemxoay/server/internal/config"
)

func main() {
	repo := filepath.Dir(filepath.Dir(config.FindRepoFile("config/game.json")))
	schemaPath := filepath.Join(repo, "proto", "schema.txt")
	s, err := parseSchema(schemaPath)
	if err != nil {
		log.Fatalf("đọc schema: %v", err)
	}

	goOut := filepath.Join(repo, "server", "internal", "wire", "wire_gen.go")
	tsOut := filepath.Join(repo, "client", "src", "net", "wire.gen.ts")
	if err := os.MkdirAll(filepath.Dir(goOut), 0o755); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(goOut, []byte(genGo(s)), 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(tsOut, []byte(genTS(s)), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("schema v%d · %d message · hash %s\n", s.Version, len(s.Messages), s.Hash)
	for _, m := range s.Messages {
		fmt.Printf("  %-10s id=%d  %d trường\n", m.Name, m.ID, len(m.Fields))
	}
	fmt.Printf("đã sinh:\n  %s\n  %s\n", goOut, tsOut)
}

const banner = "// Code generated by cmd/protogen from proto/schema.txt. DO NOT EDIT.\n" +
	"//\n" +
	"// Sửa `proto/schema.txt` rồi chạy `cd server && go run ./cmd/protogen`.\n" +
	"// Sửa tay file này thì lần sinh sau mất sạch, và tệ hơn: hai phía lệch nhau trong im lặng.\n"

func genGo(s *Schema) string {
	var b strings.Builder
	b.WriteString(banner)
	b.WriteString("\npackage wire\n\nimport (\n\t\"encoding/binary\"\n\t\"errors\"\n\t\"math\"\n)\n\n")
	fmt.Fprintf(&b, "// SchemaHash là băm của proto/schema.txt. Client gửi hash của nó lúc bắt tay;\n"+
		"// lệch nghĩa là hai bên đang nói hai thứ tiếng — từ chối kết nối thay vì đọc rác (§4.9).\n"+
		"const SchemaHash = %q\n\n", s.Hash)
	fmt.Fprintf(&b, "// SchemaVersion lấy từ dòng `version` trong schema.\nconst SchemaVersion = %d\n\n", s.Version)
	b.WriteString("// ErrShort là lỗi gói ngắn hơn số byte cần đọc.\nvar ErrShort = errors.New(\"wire: gói ngắn\")\n\n")

	b.WriteString("// Loại message — byte đầu của gói.\nconst (\n")
	for _, m := range s.Messages {
		fmt.Fprintf(&b, "\tType%s = %d\n", m.Name, m.ID)
	}
	b.WriteString(")\n\n")

	for _, m := range s.Messages {
		for _, d := range m.Doc {
			fmt.Fprintf(&b, "// %s\n", d)
		}
		fmt.Fprintf(&b, "type %s struct {\n", m.Name)
		for _, f := range m.Fields {
			c := ""
			if f.Comment != "" {
				c = " // " + f.Comment
			}
			fmt.Fprintf(&b, "\t%s %s%s\n", goName(f.Name), goType[f.Type], c)
		}
		b.WriteString("}\n\n")
		genGoEncode(&b, m)
		genGoDecode(&b, m)
	}
	b.WriteString(goHelpers)
	return b.String()
}

func genGoEncode(b *strings.Builder, m Message) {
	fmt.Fprintf(b, "// Encode nối %s vào cuối `dst` (byte loại đã nằm ở đầu gói, không lặp lại ở đây).\n", m.Name)
	fmt.Fprintf(b, "func (v %s) Encode(dst []byte) []byte {\n", m.Name)
	mask := m.maskField()
	for _, f := range m.Fields {
		if f.If != "" {
			fmt.Fprintf(b, "\tif v.%s&(1<<%d) != 0 {\n\t", goName(mask), m.bitIndex(f.If))
		}
		fmt.Fprintf(b, "\tdst = put%s(dst, v.%s)\n", strings.ToUpper(f.Type[:1])+f.Type[1:], goName(f.Name))
		if f.If != "" {
			b.WriteString("\t}\n")
		}
	}
	b.WriteString("\treturn dst\n}\n\n")
}

func genGoDecode(b *strings.Builder, m Message) {
	fmt.Fprintf(b, "// Decode%s đọc một %s từ `src`, trả về giá trị và số byte đã dùng.\n", m.Name, m.Name)
	// `err` khai MỘT lần ở đầu hàm: khai trong từng nhánh thì Go báo "err redeclared", và
	// khai trong nhánh `if` thì biến chỉ sống trong nhánh đó.
	fmt.Fprintf(b, "func Decode%s(src []byte) (%s, int, error) {\n\tvar v %s\n\tvar err error\n\tp := 0\n", m.Name, m.Name, m.Name)
	mask := m.maskField()
	for _, f := range m.Fields {
		ind := "\t"
		if f.If != "" {
			fmt.Fprintf(b, "\tif v.%s&(1<<%d) != 0 {\n", goName(mask), m.bitIndex(f.If))
			ind = "\t\t"
		}
		fmt.Fprintf(b, "%sv.%s, p, err = get%s(src, p)\n", ind, goName(f.Name), strings.ToUpper(f.Type[:1])+f.Type[1:])
		fmt.Fprintf(b, "%sif err != nil {\n%s\treturn v, p, err\n%s}\n", ind, ind, ind)
		if f.If != "" {
			b.WriteString("\t}\n")
		}
	}
	b.WriteString("\treturn v, p, nil\n}\n\n")
}

// goName đổi `ring_phase` thành `RingPhase`.
func goName(s string) string {
	parts := strings.Split(s, "_")
	for i, p := range parts {
		if p == "" {
			continue
		}
		switch p {
		case "id":
			parts[i] = "ID"
		case "ver":
			parts[i] = "Ver"
		default:
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}

const goHelpers = `
// ── đọc/ghi nguyên thuỷ ──────────────────────────────────────────────────────────────────
// Little-endian cho mọi số: JavaScript ` + "`DataView`" + ` mặc định là big-endian, nên phía
// client PHẢI truyền ` + "`true`" + `. Generator lo việc đó; đây chỉ là nửa Go.

func putU8(dst []byte, v uint8) []byte   { return append(dst, v) }
func putI8(dst []byte, v int8) []byte    { return append(dst, byte(v)) }
func putU16(dst []byte, v uint16) []byte { return binary.LittleEndian.AppendUint16(dst, v) }
func putI16(dst []byte, v int16) []byte  { return binary.LittleEndian.AppendUint16(dst, uint16(v)) }
func putU32(dst []byte, v uint32) []byte { return binary.LittleEndian.AppendUint32(dst, v) }
func putI32(dst []byte, v int32) []byte  { return binary.LittleEndian.AppendUint32(dst, uint32(v)) }

func putF32(dst []byte, v float32) []byte {
	return binary.LittleEndian.AppendUint32(dst, math.Float32bits(v))
}

// putStr ghi 1 byte độ dài + UTF-8. Chuỗi dài hơn 255 byte bị CẮT, không báo lỗi:
// tên người chơi đã được lọc ở tầng trên, và làm rơi cả gói vì một cái tên dài là đổi một
// lỗi hiển thị nhỏ thành mất kết nối.
func putStr(dst []byte, v string) []byte {
	b := []byte(v)
	if len(b) > 255 {
		b = b[:255]
	}
	dst = append(dst, byte(len(b)))
	return append(dst, b...)
}

func getU8(src []byte, p int) (uint8, int, error) {
	if p+1 > len(src) {
		return 0, p, ErrShort
	}
	return src[p], p + 1, nil
}

func getI8(src []byte, p int) (int8, int, error) {
	v, p, err := getU8(src, p)
	return int8(v), p, err
}

func getU16(src []byte, p int) (uint16, int, error) {
	if p+2 > len(src) {
		return 0, p, ErrShort
	}
	return binary.LittleEndian.Uint16(src[p:]), p + 2, nil
}

func getI16(src []byte, p int) (int16, int, error) {
	v, p, err := getU16(src, p)
	return int16(v), p, err
}

func getU32(src []byte, p int) (uint32, int, error) {
	if p+4 > len(src) {
		return 0, p, ErrShort
	}
	return binary.LittleEndian.Uint32(src[p:]), p + 4, nil
}

func getI32(src []byte, p int) (int32, int, error) {
	v, p, err := getU32(src, p)
	return int32(v), p, err
}

func getF32(src []byte, p int) (float32, int, error) {
	v, p, err := getU32(src, p)
	return math.Float32frombits(v), p, err
}

func getStr(src []byte, p int) (string, int, error) {
	n, p, err := getU8(src, p)
	if err != nil {
		return "", p, err
	}
	if p+int(n) > len(src) {
		return "", p, ErrShort
	}
	return string(src[p : p+int(n)]), p + int(n), nil
}
`
